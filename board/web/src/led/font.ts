export const GLYPH_ROWS = 7;
export const GAP = 1; // blank column between glyphs

export function glyph(ch: string): string[] {
  return G[ch] ?? G[ch.toUpperCase()] ?? G[" "]!;
}

/** Width in dot columns of a string, including inter-glyph gaps. */
export function textColumns(text: string): number {
  let w = 0;
  [...text].forEach((ch, i) => {
    w += glyph(ch)[0]!.length + (i > 0 ? GAP : 0);
  });
  return w;
}

/** Lit dots of a string as a column-major bitmap: cols[x][y]. */
export function rasterize(text: string): boolean[][] {
  const cols: boolean[][] = [];
  [...text].forEach((ch, i) => {
    if (i > 0) for (let g = 0; g < GAP; g++) cols.push(new Array(GLYPH_ROWS).fill(false));
    const rows = glyph(ch);
    const w = rows[0]!.length;
    for (let x = 0; x < w; x++) cols.push(rows.map((r) => r[x] === "#"));
  });
  return cols;
}
