"""Pilot report: per-arm cost, solve rate, failure modes and delegate share, from the pilot runs.

Feeds the pre-registration: the caps and the guardrail margin are chosen from these numbers
and from `analysis/power.py`. Writes JSON and a Markdown summary; every figure in the
Markdown comes from the JSON.
"""

from __future__ import annotations

import json
import statistics
from collections import Counter
from pathlib import Path
from typing import Annotated, Any

import typer

from harness.schema import Outcome

INFRA = {Outcome.infra_error.value}


def final_records(run_dir: Path) -> list[dict[str, Any]]:
    """The last record per instance; an infra error followed by a retry keeps the retry."""
    last: dict[str, dict[str, Any]] = {}
    for line in (run_dir / "tasks.jsonl").read_text(encoding="utf-8").splitlines():
        if line.strip():
            rec = json.loads(line)
            last[rec["instance_id"]] = rec
    return list(last.values())


def all_records(run_dir: Path) -> list[dict[str, Any]]:
    lines = (run_dir / "tasks.jsonl").read_text(encoding="utf-8").splitlines()
    return [json.loads(x) for x in lines if x.strip()]


def failure_mode(rec: dict[str, Any]) -> str:
    if rec["solved"]:
        return "solved"
    if rec["outcome"] != Outcome.unsolved.value:
        return str(rec["outcome"])
    reason = str(rec.get("error") or "")
    if "empty_patch" in reason:
        return "empty_patch"
    if "patch_apply_failed" in reason:
        return "patch_apply_failed"
    if "f2p_not_passing" in reason:
        return "f2p_not_passing"
    if "p2p_broken" in reason:
        return "p2p_broken"
    return "unsolved_other"


def arm_stats(recs: list[dict[str, Any]], attempts: list[dict[str, Any]]) -> dict[str, Any]:
    usd = [float(r["usd"]) for r in recs]
    dele = sum(float(r["usd_delegate"]) for r in recs)
    total = sum(usd)
    return {
        "n": len(recs),
        "solved": sum(1 for r in recs if r["solved"]),
        "solve_rate": sum(1 for r in recs if r["solved"]) / len(recs),
        "usd_mean": statistics.fmean(usd),
        "usd_median": statistics.median(usd),
        "usd_max": max(usd),
        "usd_total": total,
        "delegate_share": dele / total if total else 0.0,
        "turns_max": max(int(r["turns"]) for r in recs),
        "seconds_max": max(float(r["seconds"]) for r in recs),
        "delegate_calls_mean": statistics.fmean(int(r["delegate_calls"]) for r in recs),
        "failure_modes": dict(sorted(Counter(failure_mode(r) for r in recs).items())),
        "infra_retries": sum(1 for r in attempts if r["outcome"] in INFRA),
        "usd_incl_retries": sum(float(r["usd"]) for r in attempts),
    }


def build(run_dirs: list[Path]) -> dict[str, Any]:
    arms: dict[str, Any] = {}
    for d in run_dirs:
        recs = [r for r in final_records(d) if r["outcome"] not in INFRA]
        if not recs:
            continue
        arms[recs[0]["variant"]] = arm_stats(recs, all_records(d)) | {"run": d.name}
    return {"arms": arms}


def markdown(report: dict[str, Any], power: dict[str, Any] | None) -> str:
    arms = report["arms"]
    names = list(arms)
    rows = [
        ("Tasks", "n", "{:d}"),
        ("Solved", "solved", "{:d}"),
        ("Solve rate", "solve_rate", "{:.0%}"),
        ("Mean cost", "usd_mean", "${:.4f}"),
        ("Median cost", "usd_median", "${:.4f}"),
        ("Max cost", "usd_max", "${:.4f}"),
        ("Delegate share of cost", "delegate_share", "{:.0%}"),
        ("Max turns", "turns_max", "{:d}"),
        ("Max seconds", "seconds_max", "{:.0f}"),
        ("Mean delegate calls", "delegate_calls_mean", "{:.1f}"),
        ("Infra retries", "infra_retries", "{:d}"),
        ("Spend incl. retries", "usd_incl_retries", "${:.4f}"),
    ]
    out = [
        "# Pilot report",
        "",
        "Generated by `analysis/pilot_report.py` from "
        + ", ".join(f"`runs/{arms[n]['run']}`" for n in names)
        + ". Arms were forced by the runner (no Flagsmith exposure); the pilot pool is disjoint from the"
        " experiment pools.",
        "",
        "| | " + " | ".join(f"`{n}`" for n in names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for label, key, fmt in rows:
        out.append(f"| {label} | " + " | ".join(fmt.format(arms[n][key]) for n in names) + " |")
    out.append("")
    out.append("Failure modes:")
    out.append("")
    for n in names:
        modes = ", ".join(f"{k} {v}" for k, v in arms[n]["failure_modes"].items())
        out.append(f"- `{n}`: {modes}")
    if power:
        out += ["", "Power at the pilot's solve rate and cost spread (`analysis/power.py`):", ""]
        out.append(
            "| N per arm | Smallest detectable solve drop | Smallest detectable cost cut | "
            f"Power at pilot cost effect | Guardrail pass rate, no true drop (m = {power['m']:.0%}) |"
        )
        out.append("|---|---|---|---|---|")
        for r in power["grid"]:
            if r["n_per_arm"] > 100:
                break
            if r["n_per_arm"] % 10 and r["n_per_arm"] != 45:
                continue
            pce = r.get("power_at_pilot_cost_effect")
            out.append(
                f"| {r['n_per_arm']} | {r['mde_solve_pp']:.1f} pp | {r['mde_cost_pct']:.0f}% | "
                + (f"{pce:.1%}" if pce is not None else "n/a")
                + f" | {r['guardrail_pass_rate']:.1%} |"
            )
    return "\n".join(out) + "\n"


app = typer.Typer(add_completion=False)


@app.command()
def main(
    run: Annotated[list[Path], typer.Option(help="pilot run directory; repeat per arm")],
    power: Annotated[Path | None, typer.Option(help="power.json from analysis/power.py")] = None,
    out: Annotated[Path, typer.Option()] = Path("analysis/out/pilot.json"),
    md: Annotated[Path | None, typer.Option()] = None,
) -> None:
    report = build(run)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    pw = json.loads(power.read_text(encoding="utf-8")) if power and power.exists() else None
    text = markdown(report, pw)
    if md:
        md.write_text(text, encoding="utf-8")
    typer.echo(text)


if __name__ == "__main__":
    app()
